import { expect, test, type Page } from '@playwright/test'
import { tongueSamples } from '../src/clinical/tongueSamples'

async function enterConsultation(page: Page) {
  await page.goto('/')
  await page.getByRole('button', { name: '开始实训', exact: true }).click()
  await page.getByRole('button', { name: '静音', exact: true }).click()
  await expect.poll(() => page.evaluate(() => (window as any).__hospitalScene?.phase), { timeout: 50_000 }).toBe('waiting')
  for (let attempt = 0; attempt < 80; attempt++) {
    const state = await page.evaluate(() => (window as any).__hospitalScene)
    if (state?.eligible) break
    if (!state?.patient || !state.doctor || !state.camera) throw new Error('场景导航未就绪')
    const dx = state.patient.position[0] - state.doctor.position[0], dz = state.patient.position[2] - state.doctor.position[2]
    const fx = state.camera.target[0] - state.camera.position[0], fz = state.camera.target[2] - state.camera.position[2]
    const length = Math.hypot(fx, fz)
    const forward = (dx * fx + dz * fz) / length, right = (-dx * fz + dz * fx) / length
    const keys = [forward > .08 ? 'w' : forward < -.08 ? 's' : '', right > .08 ? 'd' : right < -.08 ? 'a' : ''].filter(Boolean)
    try { for (const key of keys) await page.keyboard.down(key); await page.waitForTimeout(170) }
    finally { for (const key of keys) await page.keyboard.up(key) }
  }
  await expect.poll(() => page.evaluate(() => (window as any).__hospitalScene?.eligible)).toBe(true)
  await page.keyboard.press('f')
  await page.getByRole('button', { name: '开始问诊', exact: true }).click({ timeout: 30_000 })
  await expect(page.getByLabel('问诊训练台')).toBeVisible()
}

test('case disclosure, independent tongue learning, pulse teaching and honest treatment feedback', async ({ page }) => {
  const errors: string[] = []; page.on('pageerror', (error) => errors.push(error.message))
  await enterConsultation(page)
  await expect(page.locator('.message-assistant').first()).toContainText('左上腹痛')
  await expect(page.locator('.message-assistant').first()).not.toContainText(/油腻|两天|两三天|小时/)
  const input = page.getByRole('textbox', { name: '向患者提问' })
  await input.fill('疼了多久？'); await input.press('Enter')
  await expect(page.locator('.message-assistant').last()).toContainText('两三天')
  await expect(page.locator('.message-assistant').last()).not.toContainText('油腻')
  await input.fill('疼痛是什么性质，和饮食有关吗？'); await input.press('Enter')
  await expect(page.locator('.message-assistant').last()).toContainText('胀痛')
  await expect(page.locator('.message-assistant').last()).toContainText('油腻')

  await page.getByRole('button', { name: '开始体格检查' }).click()
  await page.getByRole('button', { name: '完成检查', exact: true }).click()
  await page.getByRole('button', { name: '进入中医四诊' }).click()
  await expect(page.getByLabel('中医四诊训练台')).toBeVisible()
  await page.getByRole('button', { name: '查看舌苔', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await expect(dialog).toContainText('王旭病例舌象待教师确认')
  await dialog.getByRole('button', { name: '巩膜黄染', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('待补充')
  await dialog.getByRole('button', { name: '舌象', exact: true }).click()
  await dialog.getByRole('button', { name: '随机识图', exact: true }).click()
  const image = dialog.getByRole('img', { name: '待辨认舌象照片' })
  await expect(image).toBeVisible()
  const src = await image.getAttribute('src')
  const sample = tongueSamples.find((sample) => sample.image === src)!
  expect(sample.hasEmbeddedLabel).toBe(false)
  await dialog.getByLabel('舌象判断').selectOption(sample.label)
  await expect(image).toHaveAttribute('src', src!)
  await expect(dialog.locator('.tongue-practice-result')).toHaveCount(0)
  await dialog.getByRole('button', { name: '提交判断', exact: true }).click()
  await expect(dialog.getByRole('status')).toContainText('标签匹配')
  await page.screenshot({ path: 'verification/tcm-tongue-learning.png' })
  await dialog.getByRole('button', { name: '下一张', exact: true }).click()
  await expect(dialog.getByRole('img', { name: '待辨认舌象照片' })).not.toHaveAttribute('src', src!)
  await dialog.getByRole('button', { name: '关闭检查展示' }).click()
  await expect(page.getByRole('textbox', { name: '检查记录', exact: true })).toHaveValue('')

  await page.locator('#four-tool-feel').click()
  await page.getByRole('button', { name: '查看脉象', exact: true }).click()
  await page.emulateMedia({ reducedMotion: 'reduce' })
  const teaching = dialog.locator('.examination-teaching')
  await expect(teaching).toHaveAttribute('data-reduced-motion', 'true')
  await teaching.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(teaching.locator('.teaching-current-step strong')).toHaveText('患者伸手')
  await teaching.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(teaching.locator('.teaching-current-step strong')).toHaveText('中指定关')
  await teaching.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(teaching.locator('.teaching-current-step strong')).toHaveText('食指定位寸')
  await teaching.getByRole('button', { name: '下一步', exact: true }).click()
  await expect(teaching.locator('.teaching-current-step strong')).toHaveText('无名指定位尺')
  await expect(dialog).not.toContainText('沉滑数')
  await page.screenshot({ path: 'verification/tcm-pulse-teaching.png' })
  await teaching.getByRole('button', { name: '重播', exact: true }).click()
  await expect(teaching.locator('.teaching-current-step strong')).toHaveText('准备诊脉')
  await expect(teaching.getByRole('button', { name: '播放演示', exact: true })).toBeVisible()
  await dialog.getByRole('button', { name: '关闭检查展示' }).click()

  await page.getByRole('navigation', { name: '病例模块' }).getByRole('button', { name: /06.*处置/ }).click()
  await expect(page.getByLabel('处置训练台')).toBeVisible()
  await expect(page.getByRole('button', { name: '完成病例', exact: true })).toBeDisabled()
  const treatment = page.getByRole('textbox', { name: '第1行处置项目', exact: true })
  await treatment.fill('学生拟定的处置方案，等待教师核对')
  await page.getByRole('textbox', { name: '第1行处置类别', exact: true }).fill('')
  await page.getByRole('textbox', { name: '第1行药物名称', exact: true }).fill('学生填写药名')
  await page.getByRole('button', { name: '提交处置评价', exact: true }).click()
  await expect(page.getByLabel('处置评价结果')).toContainText('需要修改')
  await expect(page.getByLabel('处置评价结果')).toContainText('处置类别')
  await expect(page.getByLabel('处置评价结果')).toContainText('用药途径')
  await expect(page.getByRole('button', { name: '完成病例', exact: true })).toBeDisabled()
  await page.getByRole('textbox', { name: '第1行处置类别', exact: true }).fill('护理')
  await page.getByRole('textbox', { name: '第1行药物名称', exact: true }).fill('')
  await page.getByRole('button', { name: '提交处置评价', exact: true }).click()
  await expect(page.getByLabel('处置评价结果')).toContainText('待教师确认')
  await expect(page.getByLabel('处置评价结果')).not.toContainText('处置评价：通过')
  await page.getByLabel('处置评价结果').scrollIntoViewIfNeeded()
  await page.screenshot({ path: 'verification/tcm-treatment-feedback.png' })
  await treatment.fill('修改后的学生方案')
  await expect(page.getByLabel('处置评价结果')).toHaveCount(0)
  await expect(page.getByRole('button', { name: '完成病例', exact: true })).toBeDisabled()

  let release!: () => void
  const gate = new Promise<void>((resolve) => { release = resolve })
  await page.route('**/api/treatment-evaluation', async (route) => { await gate; await route.fulfill({ json: { status: 'passed' } }).catch(() => {}) })
  await page.getByRole('button', { name: '提交处置评价', exact: true }).click()
  await expect(page.getByRole('button', { name: '正在评价…', exact: true })).toBeDisabled()
  await treatment.fill('请求过程中再次修改')
  release()
  await expect(page.getByLabel('处置评价结果')).toHaveCount(0)
  await page.unroute('**/api/treatment-evaluation')
  await page.route('**/api/treatment-evaluation', (route) => route.fulfill({ status: 502, json: { error: '测试：评价服务暂不可用' } }))
  await page.getByRole('button', { name: '提交处置评价', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('测试：评价服务暂不可用')
  await expect(page.getByRole('button', { name: '完成病例', exact: true })).toBeDisabled()
  await page.unroute('**/api/treatment-evaluation')
  await page.getByRole('button', { name: '提交处置评价', exact: true }).click()
  await page.getByRole('button', { name: '结束训练（待教师确认）', exact: true }).click()
  await expect(page.getByLabel('处置训练台')).toHaveCount(0)
  expect(errors).toEqual([])
})
