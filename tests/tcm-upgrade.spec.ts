test('reduced motion and real pointer dragging preserve the tongue and pulse practice flows', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await enterConsultation(page)
  await page.getByRole('button', { name: '开始体格检查' }).click()
  await page.getByRole('button', { name: '完成检查', exact: true }).click()
  await page.getByRole('button', { name: '进入中医四诊' }).click()
  await page.getByRole('button', { name: '查看舌苔', exact: true }).click()
  const dialog = page.getByRole('dialog', { name: '望诊观察与舌象学习' })
  const tongue = dialog.getByLabel('舌诊观察实训')
  await expect(tongue).toHaveAttribute('data-reduced-motion', 'true')
  await expect(tongue.getByRole('img', { name: '老师提供的待辨认舌象照片' })).toBeVisible()
  await expect(tongue.locator('.tongue-action-scene img')).toHaveCount(1)
  await expect(tongue.getByLabel('舌象判断', { exact: true })).toBeEnabled()
  await tongue.getByLabel('舌象观察笔记').fill('观察舌色与舌苔')
  await tongue.getByRole('button', { name: '放大舌象照片' }).click()
  await expect(page.getByRole('dialog', { name: '舌象原图大图' })).toBeVisible()
  await page.keyboard.press('Escape')
  await expect(dialog).toBeVisible()
  await expect(page.getByRole('dialog', { name: '舌象原图大图' })).toHaveCount(0)
  await page.screenshot({ path: 'verification/realistic-tongue-observation.png' })
  await dialog.getByRole('button', { name: '关闭检查展示' }).click()
  await page.locator('#four-tool-feel').click()
  await page.getByRole('button', { name: '查看脉象', exact: true }).click()
  const pulse = page.getByLabel('脉诊操作实训')
  await expect(pulse.getByRole('group', { name: '拖动医生手部', exact: true })).toBeVisible()
  await expect(pulse.getByRole('button', { name: '选择二指', exact: true })).toHaveCount(0)
  await expect(pulse.getByText('操作反馈', { exact: true })).toHaveCount(0)
  await expect(pulse.getByRole('region', { name: '脉象判断结果' })).toHaveCount(0)
  const canvas = pulse.getByLabel('脉诊照片操作画布')
  const hand = pulse.getByRole('group', { name: '拖动医生手部', exact: true })
  const placeHand = async (count: 1 | 3) => {
    await canvas.scrollIntoViewIfNeeded()
    const canvasBox = (await canvas.boundingBox())!, handBox = (await hand.boundingBox())!
    const ideal = idealHandPosition(count)
    const current = { x: (handBox.x + handBox.width / 2 - canvasBox.x) / canvasBox.width * 100, y: (handBox.y + handBox.height / 2 - canvasBox.y) / canvasBox.height * 100 }
    const grab = { x: handBox.x + handBox.width * .5, y: handBox.y + handBox.height * .65 }
    await page.mouse.move(grab.x, grab.y); await page.mouse.down()
    await page.mouse.move(grab.x + (ideal.x - current.x) / 100 * canvasBox.width, grab.y + (ideal.y - current.y) / 100 * canvasBox.height, { steps: 12 })
    await page.mouse.up()
    await pulse.getByRole('button', { name: '检查位置', exact: true }).click()
    await expect(pulse.locator('.pulse-position-status')).toContainText('位置已对齐')
  }
  await pulse.getByRole('button', { name: '选择一指', exact: true }).click()
  await placeHand(1)
  await pulse.getByRole('button', { name: '触诊中指关位', exact: true }).click()
  const readings = pulse.getByLabel('触诊记录')
  await expect(readings).toContainText('搏动较轻，不易触及')
  await pulse.getByRole('button', { name: '选择三指', exact: true }).click()
  await placeHand(3)
  for (const label of ['中指关位', '食指寸位', '无名指尺位']) {
    const tip = pulse.getByRole('button', { name: `触诊${label}`, exact: true })
    await tip.scrollIntoViewIfNeeded()
    const box = (await tip.boundingBox())!
    await page.mouse.move(box.x + box.width / 2, box.y + box.height / 2)
    await page.mouse.down()
    await expect(readings).toContainText('较深处搏动清楚，往来流畅，频率较快')
    await page.waitForTimeout(650)
    await page.mouse.up()
  }
  await expect(pulse.getByRole('region', { name: '脉象判断结果' })).toHaveCount(0)
  await expect(pulse).not.toContainText('沉滑数')
  await pulse.getByRole('checkbox', { name: '沉', exact: true }).check()
  await pulse.getByRole('button', { name: '提交脉象判断', exact: true }).click()
  const result = pulse.getByRole('region', { name: '脉象判断结果' })
  await expect(result).toContainText('尚未识别：滑、数')
  await pulse.getByRole('checkbox', { name: '滑', exact: true }).check()
  await pulse.getByRole('checkbox', { name: '数', exact: true }).check()
  await pulse.getByRole('button', { name: '提交脉象判断', exact: true }).click()
  await expect(result).toContainText('你的判断与病例参考一致')
  await expect(result).toContainText('病例参考：沉滑数')
  await pulse.getByRole('button', { name: '重置练习', exact: true }).click()
  await expect(result).toHaveCount(0)
  await expect(readings).toContainText('尚未轻取')
  await expect(pulse.getByRole('button', { name: '提交脉象判断', exact: true })).toBeDisabled()
})
