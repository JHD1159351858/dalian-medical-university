class Projection:
    """Orthographic frontal portrait registration; -Y is forward, +Z is up."""
    def __init__(self, s):
        (lx, ly), (rx, ry) = s['eyes']
        self.cx, self.cy = (lx+rx)/2, (ly+ry)/2
        d = hypot(rx-lx, ry-ly)
        self.c, self.s = (rx-lx)/d, (ry-ly)/d
        self.sx = d / (.277 * s['width'])
        self.eye_opening = .24 if s['age'] < 60 else .15
        self.eye_z = .334 if s['age'] < 60 else .321
        jaw_x, jaw_y = s['chin']
        self.sy = (-(jaw_x-self.cx)*self.s + (jaw_y-self.cy)*self.c) / self.eye_z
        # The nose/chin axis may lean independently of the eye line.
        self.shear = ((jaw_x-self.cx)*self.c + (jaw_y-self.cy)*self.s) / self.eye_z

    def eye_distance(self, distance):
        # Keep the portrait's rounded almond openings when fitting its taller face onto a chibi skull.
        return distance*(1-self.eye_opening*np.exp(-(distance/.064)**2))

    def project(self, x, z):
        h = self.eye_distance(self.eye_z-z)
        side = self.sx*x + self.shear*h
        return self.cx + side*self.c - h*self.sy*self.s, self.cy + side*self.s + h*self.sy*self.c

    def unproject(self, pt):
        dx,dy = pt[0]-self.cx,pt[1]-self.cy
        h = (-dx*self.s+dy*self.c) / self.sy
        distance = h
        for _ in range(4):
            r = (distance/.064)**2
            derivative = 1-self.eye_opening*np.exp(-r)*(1-2*r)
            distance -= (self.eye_distance(distance)-h)/derivative
        return ((dx*self.c+dy*self.s-self.shear*h)/self.sx, self.eye_z-distance)

